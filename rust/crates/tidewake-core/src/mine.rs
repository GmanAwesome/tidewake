/// Water, dormant spire and awake spire. Matches `items.UNBREAKABLE`.
pub fn unbreakable(id: u8) -> bool {
    id == 11 || id == 22 || id == 23
}

/// Wooden through aetherite tools occupy item ids 274..293, four kinds per tier.
pub fn tool_of(item: u16) -> Option<(u8, u8)> {
    if (274..=293).contains(&item) {
        let i = item - 274;
        Some(((i % 4) as u8 + 1, (i / 4) as u8))
    } else {
        None
    }
}

/// Seconds to break `mat` with `item` in hand, and whether it drops.
pub fn mine_time(mat: u8, item: u16) -> (f32, bool) {
    if mat as usize >= HARD.len() {
        return (0.15, true);
    }
    let (mut secs, kind, tier) = HARD[mat as usize];
    let (have_kind, have_tier) = tool_of(item).unwrap_or((0, 0));
    let drops = if kind != 0 && have_kind == kind {
        secs /= TIER_SPEED[have_tier as usize];
        have_tier + 1 >= tier
    } else {
        if kind == 1 && tier > 0 {
            secs *= 1.6;
        }
        tier == 0
    };
    let name = materials::MATS[mat as usize].name;
    if have_kind == 4 && name.eq_ignore_ascii_case("canopy") {
        secs /= 3.0;
    }
    (secs.max(0.05), drops)
}

/// `(item id, count)` dropped by a broken cell. `roll` is in 0..1, standing in for `random.random`.
pub fn drops_for(mat: u8, roll: f32) -> Vec<(u16, u16)> {
    let name = materials::MATS.get(mat as usize).map(|m| m.name.to_ascii_lowercase()).unwrap_or_default();
    let key = name.replace(' ', "_");
    let sprout = materials::id_named("sprout").unwrap_or(0) as u16;
    let bush = materials::id_named("berry_bush").unwrap_or(0) as u16;
    let petals = materials::id_named("petals").unwrap_or(0) as u16;
    match key.as_str() {
        "turf" => {
            let mut out = vec![(2, 1)];
            if roll < 0.18 {
                out.push((312, 1));
            }
            out
        }
        "farmland" => vec![(2, 1)],
        "loam" => {
            let mut out = vec![(2, 1)];
            if roll < 0.08 {
                out.push((313, 1));
            }
            out
        }
        "canopy" => {
            let mut out = Vec::new();
            if roll < 0.10 {
                out.push((sprout, 1));
            }
            if roll < 0.08 {
                out.push((256, 1));
            }
            out
        }
        "emberite_ore" => vec![(257, 1 + u16::from(roll < 0.3))],
        "aetherite_ore" => vec![(260, 1)],
        "berry_bush" => {
            let n = 1 + ((roll * 2.99) as u16).min(2);
            let mut out = vec![(266, n)];
            if roll < 0.35 {
                out.push((bush, 1));
                out.push((314, 1));
            }
            out
        }
        "petals" => {
            let mut out = Vec::new();
            if roll < 0.5 {
                out.push((petals, 1));
            }
            if roll < 0.12 {
                out.push((312, 1));
            }
            out
        }
        _ => vec![(mat as u16, 1)],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bare_hands_and_a_wooden_pick_match_items_py() {
        let (secs, drops) = mine_time(1, 0);
        assert!((secs - 4.8).abs() < 1e-3, "{secs}");
        assert!(!drops);
        let (secs, drops) = mine_time(1, 274);
        assert!((secs - 1.5).abs() < 1e-3, "{secs}");
        assert!(drops);
        let (secs, drops) = mine_time(3, 0);
        assert!((secs - 0.95).abs() < 1e-3, "{secs}");
        assert!(drops);
        assert_eq!(drops_for(3, 0.5), vec![(2, 1)]);
        assert!(drops_for(3, 0.0).iter().any(|d| d.0 == 312));
        assert!(unbreakable(22));
    }
}
